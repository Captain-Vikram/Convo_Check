/**
 * Format planner output for display
 */
export function formatPlannerExplanation(plan: PlannerOutput): string {
  const lines: string[] = [];
  
  lines.push(`🎯 Search Strategy:`);
  lines.push(`   Intent: ${plan.queryIntent}`);
  
  if (plan.budget) {
    const budgetStr = plan.budget.max 
      ? `₹${plan.budget.max.toLocaleString('en-IN')} max`
      : plan.budget.approximate 
      ? `~₹${plan.budget.approximate.toLocaleString('en-IN')}`
      : plan.budget.min 
      ? `₹${plan.budget.min.toLocaleString('en-IN')}+`
      : 'Flexible';
    lines.push(`   Budget: ${budgetStr}`);
  }
  
  if (plan.priorities.length > 0) {
    lines.push(`   Priorities: ${plan.priorities.join(', ')}`);
  }
  
  if (plan.brands?.preferred && plan.brands.preferred.length > 0) {
    lines.push(`   Brands: ${plan.brands.preferred.join(', ')}`);
  }
  
  lines.push(`   Strategies (${plan.candidateQueries.length}):`);
  plan.candidateQueries.forEach((cq, i) => {
    const percent = (cq.weight * 100).toFixed(0);
    lines.push(`     ${i + 1}. "${cq.query}" (${percent}%)`);
  });
  
  return lines.join('\n');
}

/**
 * Extract search parameters from planner output
 */
export function extractSearchParams(plan: PlannerOutput): {
  minPrice?: number | undefined;
  maxPrice?: number | undefined;
  location: string;
} {
  const min = plan.budget?.min;
  const max = plan.budget?.max;

  return {
    minPrice: typeof min === 'number' ? min : undefined,
    maxPrice: typeof max === 'number' ? max : undefined,
    location: 'India',
  };
}

let cachedPlannerModel: LanguageModel | null = null;
let cachedPlannerModelName: string | null = null;
let cachedProvider: ReturnType<typeof createGoogleGenerativeAI> | null = null;
let cachedProviderKey: string | null = null;

function getPlannerProvider(apiKey: string) {
  if (!cachedProvider || cachedProviderKey !== apiKey) {
    cachedProvider = createGoogleGenerativeAI({ apiKey });
    cachedProviderKey = apiKey;
    cachedPlannerModel = null;
    cachedPlannerModelName = null;
  }
  return cachedProvider;
}

async function getPlannerModel(modelOverride?: string): Promise<LanguageModel> {
  const { apiKey, model: defaultModelName } = getAgentConfig('agent5');
  const provider = getPlannerProvider(apiKey);

  if (!modelOverride) {
    if (!cachedPlannerModel || cachedPlannerModelName !== defaultModelName) {
      cachedPlannerModel = provider(defaultModelName);
      cachedPlannerModelName = defaultModelName;
    }
    return cachedPlannerModel;
  }

  return provider(modelOverride);
}
