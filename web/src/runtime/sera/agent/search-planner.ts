/**
 * Fallback planner when LLM fails - uses heuristics
 */
export function fallbackPlanner(
  userMessage: string,
  context: PlannerContext,
  maxCandidates: number
): PlannerOutput {
  // Extract budget
  const budget = extractBudget(userMessage);
  
  // Detect product category
  const category = detectCategory(userMessage);
  
  // Extract brand mentions
  const brands = extractBrands(userMessage, category);
  
  // Generate candidate queries
  const candidates = generateFallbackCandidates(
    userMessage,
    category,
    budget,
    brands,
    maxCandidates
  );
  
  return {
    queryIntent: `Search for ${category} ${budget.max ? `under ₹${budget.max}` : ''}`,
    budget: Object.keys(budget).length > 0 ? budget : undefined,
    priorities: detectPriorities(userMessage, category),
    brands: brands.length > 0 ? { preferred: brands } : undefined,
    candidateQueries: candidates,
    marketContext: 'Using fallback heuristic planner',
  };
}

/**
 * Extract budget from user message
 */
function extractBudget(message: string): Budget {
  const budget: Budget = {};
  
  // Pattern: "under 50000", "below 50k"
  const underMatch = message.match(/(?:under|below|max|upto|up to)\s*(?:₹|rs\.?|inr)?\s*(\d+)k?/i);
  if (underMatch?.[1]) {
    const value = parseFloat(underMatch[1]);
    budget.max = value > 100 ? value : value * 1000;
  }
  
  // Pattern: "around 40000", "about 40k"
  const aroundMatch = message.match(/(?:around|about|approx|near)\s*(?:₹|rs\.?|inr)?\s*(\d+)k?/i);
  if (aroundMatch?.[1]) {
    const value = parseFloat(aroundMatch[1]);
    budget.approximate = value > 100 ? value : value * 1000;
  }
  
  // Pattern: "25000 to 35000", "25k-35k"
  const rangeMatch = message.match(/(\d+)k?\s*(?:to|-)\s*(\d+)k?/i);
  if (rangeMatch?.[1] && rangeMatch[2]) {
    const min = parseFloat(rangeMatch[1]);
    const max = parseFloat(rangeMatch[2]);
    budget.min = min > 100 ? min : min * 1000;
    budget.max = max > 100 ? max : max * 1000;
  }
  
  return budget;
}

/**
 * Detect product category
 */
function detectCategory(message: string): string {
  const msg = message.toLowerCase();
  
  if (/\b(phone|mobile|smartphone)\b/.test(msg)) return 'smartphone';
  if (/\b(laptop|notebook)\b/.test(msg)) return 'laptop';
  if (/\b(tablet|ipad)\b/.test(msg)) return 'tablet';
  if (/\b(headphone|earphone|earbud|airpod)\b/.test(msg)) return 'audio device';
  if (/\b(watch|smartwatch)\b/.test(msg)) return 'smartwatch';
  if (/\b(tv|television)\b/.test(msg)) return 'television';
  if (/\b(camera)\b/.test(msg)) return 'camera';
  if (/\b(gaming|console|ps5|xbox)\b/.test(msg)) return 'gaming';
  
  return 'product';
}

/**
 * Extract brand mentions
 */
function extractBrands(message: string, category: string): string[] {
  const brands: string[] = [];
  const msg = message.toLowerCase();
  
  // Common brands by category
  const brandsByCategory: Record<string, string[]> = {
    smartphone: ['realme', 'xiaomi', 'samsung', 'oneplus', 'poco', 'vivo', 'oppo', 'apple', 'nothing'],
    laptop: ['hp', 'dell', 'lenovo', 'asus', 'acer', 'apple', 'msi', 'lg'],
    tablet: ['samsung', 'apple', 'lenovo', 'xiaomi'],
    'audio device': ['boat', 'oneplus', 'realme', 'sony', 'jbl', 'bose', 'apple'],
    smartwatch: ['noise', 'boat', 'fire-boltt', 'samsung', 'apple', 'amazfit'],
    television: ['samsung', 'lg', 'sony', 'mi', 'oneplus', 'tcl'],
  };
  
  const possibleBrands = brandsByCategory[category] || [];
  
  for (const brand of possibleBrands) {
    if (msg.includes(brand)) {
      brands.push(brand.charAt(0).toUpperCase() + brand.slice(1));
    }
  }
  
  return brands;
}

/**
 * Detect feature priorities from message
 */
function detectPriorities(message: string, category: string): string[] {
  const priorities: string[] = [];
  const msg = message.toLowerCase();
  
  // Common priorities
  if (/\b(camera|photo|picture)\b/.test(msg)) priorities.push('camera');
  if (/\b(battery|charge)\b/.test(msg)) priorities.push('battery life');
  if (/\b(gaming|game|fps)\b/.test(msg)) priorities.push('gaming performance');
  if (/\b(display|screen|amoled)\b/.test(msg)) priorities.push('display quality');
  if (/\b(fast|quick|speed|performance)\b/.test(msg)) priorities.push('performance');
  if (/\b(storage|gb|memory)\b/.test(msg)) priorities.push('storage');
  if (/\b(5g|network)\b/.test(msg)) priorities.push('5G connectivity');
  if (/\b(light|portable|thin)\b/.test(msg)) priorities.push('portability');
  
  // Default priorities by category
  if (priorities.length === 0) {
    const defaultPriorities: Record<string, string[]> = {
      smartphone: ['camera', 'battery life', 'performance'],
      laptop: ['performance', 'portability', 'battery life'],
      'audio device': ['sound quality', 'battery life', 'comfort'],
      smartwatch: ['battery life', 'fitness tracking', 'display'],
    };
    
    priorities.push(...(defaultPriorities[category] || ['quality', 'value for money']));
  }
  
  return priorities;
}

/**
 * Generate fallback candidate queries
 */
function generateFallbackCandidates(
  userMessage: string,
  category: string,
  budget: Budget,
  brands: string[],
  maxCandidates: number
): CandidateQuery[] {
  const candidates: CandidateQuery[] = [];
  
  // Build base query
  const budgetStr = budget.max 
    ? `under ${budget.max}` 
    : budget.approximate 
    ? `around ${budget.approximate}` 
    : '';
  
  // Primary query: user message + India
  candidates.push({
    query: `${userMessage} India`,
    weight: 0.4,
    rationale: 'Direct user query with India context',
  });
  
  // Secondary query: category + budget + India
  if (budgetStr) {
    candidates.push({
      query: `${category} ${budgetStr} India`,
      weight: 0.3,
      rationale: 'Category-focused with budget',
    });
  }
  
  // Brand-specific queries
  if (brands.length > 0) {
    const brandWeight = 0.3 / brands.length;
    brands.slice(0, maxCandidates - candidates.length).forEach(brand => {
      candidates.push({
        query: `${brand} ${category} ${budgetStr} India`.trim(),
        weight: brandWeight,
        rationale: `${brand} specific search`,
      });
    });
  }
  
  // Generic fallback if we don't have enough
  if (candidates.length < 2) {
    candidates.push({
      query: `best ${category} India ${new Date().getFullYear()}`,
      weight: 0.3,
      rationale: 'Generic best-of search',
    });
  }
  
  // Limit to maxCandidates
  const limited = candidates.slice(0, maxCandidates);
  
  // Normalize weights
  return normalizeCandidateWeights({ 
    queryIntent: '', 
    priorities: [], 
    candidateQueries: limited 
  }).candidateQueries;
}

